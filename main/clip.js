'use strict';
// The clipboard link of a control session, main-process half. While the sharer's Allow covers the
// clipboard, text copied on one machine is put on the other's clipboard, both ways. This is the only
// code that reads or writes the OS clipboard for that. Every backend call goes through one promise
// chain, and no text is logged, shown or kept beyond the last one compared.
//
// One link per app. On the sharer's machine (role 'give') it lives only with the control grant that
// allowed it: it starts with that grant's token, the grant is asked again before every read and every
// write, and a link that ended is not started again under the same grant (main/grant.js clipOk,
// clipSpent). There the clipboard is read on a timer, because the copy is made by the contact who
// drives the machine. On the viewer's machine (role 'take') there is no timer: the clipboard is read
// when the page says the user came back to the shared screen (poke).
// Kept apart from main.js so that it can be tested without a window: `backend` is Electron's
// clipboard, or one in memory (--clip-fake).
const MAX_BYTES = 65536;   // UTF-8 bytes of one text, the bound of a chat message (core/store.js)
const POLL_MS = 500;
// A password manager marks what it copies so that clipboard tools leave it alone. Text that carries
// one of these is not read at all.
const MARKERS = { darwin: ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType'], win32: ['ExcludeClipboardContentFromMonitorProcessing'], linux: ['x-kde-passwordManagerHint'] };
const norm = (t) => String(t == null ? '' : t).replace(/\r\n?/g, '\n');

// enabled(): the Settings switch. grant: { clipOk(pub, token), clipSpent(token) }.
function createClipLink({ backend, platform, enabled, grant }) {
  let link = null, seq = 0, chain = Promise.resolve();   // link: { id, pub, role, token, last, peer, timer, queued }
  const api = { onText: null, onNote: null, onStop: null };
  const run = (fn) => { const p = chain.then(fn); chain = p.catch(() => {}); return p; };
  const may = (l) => enabled() && (l.role !== 'give' || grant.clipOk(l.pub, l.token));
  async function concealed() {
    for (const f of MARKERS[platform] || []) { try { if (await backend.has(`electron application/osclipboard;format="${f}"`)) return true; } catch {} }
    return false;
  }

  function stop(why) {
    const l = link;
    if (!l) return false;
    link = null; clearInterval(l.timer);
    if (l.role === 'give') grant.clipSpent(l.token);   // off is final for the grant
    if (api.onStop) api.onStop(l.id, why);
    return true;
  }

  // What is on the clipboard when the link starts is the baseline: it was copied before anyone agreed
  // to share, and it is never sent. A link whose baseline cannot be read does not start.
  function start({ pub, role, token }) {
    role = role === 'give' ? 'give' : 'take';
    if (!enabled()) return Promise.resolve({ ok: false, reason: 'off' });
    if (role === 'give' && !grant.clipOk(pub, token)) return Promise.resolve({ ok: false, reason: 'nogrant' });
    if (link) { if (role === 'give') grant.clipSpent(token); return Promise.resolve({ ok: false, reason: 'busy' }); }
    const l = link = { id: String(++seq), pub, role, token: role === 'give' ? token : null, last: null, peer: null, timer: null, queued: false };
    return run(async () => {
      let t = null; try { t = norm(await backend.readText()); } catch {}
      if (link !== l) return { ok: false, reason: 'stopped' };
      if (t === null) { stop('read failed'); return { ok: false, reason: 'read' }; }
      l.last = t;
      if (role === 'give') l.timer = setInterval(() => tick(l), POLL_MS);
      return { ok: true, id: l.id };
    });
  }

  // One look at the clipboard. Sent on: a text that is new since the last look, did not come from the
  // peer, has no NUL and fits the bound. A read that is still waiting stands for the ones after it.
  function tick(l) {
    if (link !== l || l.queued) return;
    l.queued = true;
    run(async () => {
      l.queued = false;
      if (link !== l) return;
      if (!may(l)) { stop('not allowed'); return; }
      if (await concealed()) return;
      const t = norm(await backend.readText());
      if (link !== l || !t || t === l.last) return;
      l.last = t;
      if (t === l.peer) return;
      if (t.includes('\0')) { if (api.onNote) api.onNote(l.id, 'refused'); return; }
      if (Buffer.byteLength(t) > MAX_BYTES) { if (api.onNote) api.onNote(l.id, 'big'); return; }
      if (api.onText) api.onText(l.id, t);
    }).catch(() => {});
  }
  function poke(id) { if (link && link.id === id && link.role === 'take') tick(link); }

  // A text from the peer goes onto this clipboard. It is remembered as theirs, so the next look does
  // not send it back; what the OS made of it is read once, so that is not taken for a new copy either.
  // Remembered only once it is written: a write that throws leaves `last` as it was, so the text that is
  // still on the clipboard (it can be the one from before the link) is not taken for a new copy. And
  // nothing is read back for a link that stopped while the write was under way.
  function apply(id, text) {
    return run(async () => {
      const l = link;
      if (!l || l.id !== id || typeof text !== 'string' || !text || text.includes('\0') || Buffer.byteLength(text) > MAX_BYTES) return false;
      if (!may(l)) { stop('not allowed'); return false; }
      const t = norm(text);
      if (t === l.last) { l.peer = t; return true; }
      await backend.writeText(text);
      if (link !== l) return true;
      l.peer = l.last = t;
      try { const now = norm(await backend.readText()); if (link === l) l.last = now; } catch {}
      return true;
    });
  }

  const stopFor = (token, why) => (!!link && link.role === 'give' && link.token === token ? stop(why) : false);
  const status = () => ({ on: !!link, id: link ? link.id : null, pub: link ? link.pub : null, role: link ? link.role : null });
  return Object.assign(api, { start, poke, apply, stop, stopFor, status });
}

module.exports = { createClipLink, MAX_BYTES, POLL_MS };
